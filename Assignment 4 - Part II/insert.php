<?php

// Database connection
$host = "database";
$dbname = "BrandonMcCulloch";
$username = "db_BrandonMcCulloch";
$password = getenv("DB_PASSWORD");


header("Content-Type: text/plain; charset=UTF-8");

// Require GET request
if ($_SERVER["REQUEST_METHOD"] !== "GET") {
    http_response_code(405);
    exit("Error: GET request required.");
}


// Read Base64 message directly from URL
$encoded = $_SERVER["QUERY_STRING"] ?? "";

// Decode Base64 message
$decoded = base64_decode($encoded, true);

if ($decoded === false || $encoded === "") {
    http_response_code(400);
    exit("Error: Invalid Base64 message.");
}

// Parse decoded message into an array
parse_str($decoded, $values);

// Extract sensor values
$node = $values["nodeId"] ?? "";
$temp = $values["nodeTemp"] ?? null;
$humidity = $values["nodeHumidity"] ?? null;
$time = $values["timeReceived"] ?? "";

// Validate required values
if ($node === "" || !is_string($node) ||
    !is_scalar($temp) || !is_scalar($humidity) ||
    !is_numeric($temp) || !is_numeric($humidity) ||
    !is_finite((float)$temp) || !is_finite((float)$humidity)) {
    http_response_code(400);
    exit("Error: Invalid or missing sensor values.");
}

if (strlen($node) > 10) {
    http_response_code(400);
    exit("Error: Node name is too long.");
}

// Validate optional timestamp
if (!is_string($time)) {
    http_response_code(400);
    exit("Error: Invalid timestamp.");
}

if ($time !== "") {
    $date = DateTimeImmutable::createFromFormat(
        "!Y-m-d H:i:s", $time
    );

    if (!$date || $date->format("Y-m-d H:i:s") !== $time) {
        http_response_code(400);
        exit("Error: Use YYYY-MM-DD HH:MM:SS.");
    }
}

try {
    $pdo = new PDO(
        "mysql:host=$host;dbname=$dbname;charset=utf8mb4",
        $username,
        $password,
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
    );

    // Verify node is registered
    $check = $pdo->prepare(
        "SELECT node_name FROM sensor_register
         WHERE node_name = :node"
    );
    $check->execute(["node" => $node]);

    if (!$check->fetch()) {
        http_response_code(400);
        exit("Error: Sensor node is not registered.");
    }

    // Insert reading with supplied time
    if ($time !== "") {
        $sql = "INSERT INTO sensor_data
                (node_name, time_received, temperature, humidity)
                VALUES (:node, :time, :temp, :humidity)";

        $params = [
            "node" => $node,
            "time" => $time,
            "temp" => $temp,
            "humidity" => $humidity
        ];
    } else {
        // Let MariaDB generate the timestamp
        $sql = "INSERT INTO sensor_data
                (node_name, time_received, temperature, humidity)
                VALUES (:node, CURRENT_TIMESTAMP, :temp, :humidity)";

        $params = [
            "node" => $node,
            "temp" => $temp,
            "humidity" => $humidity
        ];
    }

    $stmt = $pdo->prepare($sql);
    $stmt->execute($params);

echo "Sensor data inserted successfully.\n\n";

echo "Decoded Parameters:\n";
echo "nodeId = " . $node . "\n";
echo "nodeTemp = " . $temp . "\n";
echo "nodeHumidity = " . $humidity . "\n";
echo "timeReceived = " . ($time !== "" ? $time : "Generated by database") . "\n";

} catch (PDOException $e) {
    $code = (int)($e->errorInfo[1] ?? 0);

    if ($code === 1062) {
        http_response_code(409);
        echo "Error: Duplicate timestamp for this node.";
    } elseif ($code === 1452) {
        http_response_code(400);
        echo "Error: Sensor node is not registered.";
    } elseif ($code === 4025 || $code === 1264) {
        http_response_code(400);
        echo "Error: Sensor values violate database constraints.";
    } else {
        http_response_code(500);
        echo "Error: Database operation failed.";
    }

    error_log($e->getMessage());
}
?>
